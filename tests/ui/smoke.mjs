import { chromium } from 'playwright';
const url = process.env.URL || 'http://127.0.0.1:5180/';
const out = process.env.OUT || '/tmp/shots';
import fs from 'fs'; fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const page = await browser.newPage({ viewport: { width: 1500, height: 900 } });
const errors = [];
page.on('pageerror', e => errors.push('pageerror: ' + e.message));
page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
await page.goto(url);
await page.waitForTimeout(800);
await page.screenshot({ path: out + '/01-home.png' });
// open snapshot via Ouvrir
await page.click('#btnOpen');
await page.waitForSelector('.kpi .value');
await page.waitForTimeout(400);
await page.screenshot({ path: out + '/02-dashboard.png' });
await page.click('nav.tabs button[data-view=tree]');
await page.waitForTimeout(500);
await page.click('#tree .trow >> text=Direction');
await page.waitForSelector('#folderPanel table.data');
await page.screenshot({ path: out + '/03-tree.png' });
await page.click('nav.tabs button[data-view=map]');
await page.fill('#mapWho', 'alice');
await page.waitForSelector('#mapSuggest button');
await page.click('#mapSuggest button');
await page.waitForSelector('#mapLegend .lv');
await page.waitForTimeout(600);
await page.click('#mapTree .trow >> text=Compta');
await page.waitForSelector('#explainPanel .result3');
await page.waitForTimeout(500);
await page.screenshot({ path: out + '/04-map.png' });
await page.click('nav.tabs button[data-view=findings]');
await page.waitForTimeout(300);
await page.screenshot({ path: out + '/05-findings.png' });
console.log(errors.length ? errors.join('\n') : 'NO ERRORS');
await browser.close();
